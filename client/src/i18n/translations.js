export const round2 = (n) => Math.round((Number(n) || 0) * 100) / 100;

export function formatMoney(n, currency = '$') {
  const v = round2(n);
  return currency + (Number.isInteger(v) ? v : v.toFixed(2));
}

export function formatDateLabel(iso, lang = 'so') {
  if (!iso) return '—';
  try {
    const d = new Date(iso + (iso.includes('T') ? '' : 'T00:00:00'));
    if (isNaN(d.getTime())) return iso;
    return lang === 'so'
      ? d.getDate() + ' ' + SO_MONTH_SHORT[d.getMonth()]
      : d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
  } catch (e) {
    return iso;
  }
}

export function formatDateLong(iso, lang = 'so') {
  if (!iso) return '—';
  try {
    const d = new Date(iso + (iso.includes('T') ? '' : 'T00:00:00'));
    if (isNaN(d.getTime())) return iso;
    return lang === 'so'
      ? d.getDate() + ' ' + SO_MONTH[d.getMonth()] + ' ' + d.getFullYear()
      : d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
  } catch (e) {
    return iso;
  }
}

export function formatMonthName(key, lang = 'so') {
  if (!key) return '';
  try {
    const d = new Date(key + '-01T00:00:00');
    if (isNaN(d.getTime())) return key;
    return lang === 'so'
      ? SO_MONTH[d.getMonth()] + ' ' + d.getFullYear()
      : d.toLocaleDateString('en-US', { month: 'long', year: 'numeric' });
  } catch (e) {
    return key;
  }
}

export function formatTimeLabel(timeStr, lang = 'so') {
  if (!timeStr) return '';
  const parts = timeStr.split(':');
  if (parts.length < 2) return timeStr;
  const h = parseInt(parts[0], 10);
  const m = parseInt(parts[1], 10);
  const hh = h % 12 === 0 ? 12 : h % 12;
  const clock = hh + ':' + String(m).padStart(2, '0');
  if (lang !== 'so') return clock + ' ' + (h >= 12 ? 'PM' : 'AM');
  const part = h < 12 ? 'subaxnimo' : (h < 16 ? 'duhurnimo' : (h < 19 ? 'galabnimo' : 'habeennimo'));
  return clock + ' ' + part;
}

